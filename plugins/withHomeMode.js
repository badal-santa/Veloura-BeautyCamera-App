const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidManifest,
  withAndroidStyles,
  withDangerousMod,
} = require('expo/config-plugins');

const LAUNCHER = '.LauncherActivity';

/**
 * Veloura "Home mode".
 *
 * The launcher runs in its own activity + task (separate from the regular app),
 * so pressing Home / the home gesture really minimizes Veloura. The activity has
 * a HOME intent filter and is disabled until the user turns Home mode on (the
 * veloura-launcher native module toggles it).
 */
function withLauncherManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    // Drop the old alias-based setup if present.
    app['activity-alias'] = (app['activity-alias'] ?? []).filter((a) => a.$['android:name'] !== '.HomeAlias');
    app.activity = (app.activity ?? []).filter((a) => a.$['android:name'] !== LAUNCHER);
    app.activity.push({
      $: {
        'android:name': LAUNCHER,
        'android:label': '@string/app_name',
        'android:enabled': 'false',
        'android:exported': 'true',
        'android:launchMode': 'singleTask',
        'android:taskAffinity': 'veloura.launcher',
        'android:excludeFromRecents': 'true',
        'android:stateNotNeeded': 'true',
        'android:resumeWhilePausing': 'true',
        'android:clearTaskOnLaunch': 'true',
        'android:screenOrientation': 'portrait',
        'android:windowSoftInputMode': 'adjustPan',
        'android:theme': '@style/Theme.App.Launcher',
        'android:configChanges':
          'keyboard|keyboardHidden|orientation|screenSize|screenLayout|uiMode|smallestScreenSize|assetsPaths',
      },
      'intent-filter': [
        {
          action: [{ $: { 'android:name': 'android.intent.action.MAIN' } }],
          category: [
            { $: { 'android:name': 'android.intent.category.HOME' } },
            { $: { 'android:name': 'android.intent.category.DEFAULT' } },
          ],
        },
      ],
    });
    return cfg;
  });
}

/** The launcher window shows the system wallpaper; the regular app stays opaque. */
function withLauncherTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    const res = cfg.modResults.resources;
    res.style = (res.style ?? []).filter((s) => s.$.name !== 'Theme.App.Launcher');
    res.style.push({
      $: { name: 'Theme.App.Launcher', parent: 'AppTheme' },
      item: [
        { $: { name: 'android:windowShowWallpaper' }, _: 'true' },
        { $: { name: 'android:windowBackground' }, _: '@android:color/transparent' },
        { $: { name: 'android:windowIsTranslucent' }, _: 'false' },
      ],
    });
    // Older builds put the wallpaper on the main theme — remove it there.
    const appTheme = res.style.find((s) => s.$.name === 'AppTheme');
    if (appTheme) {
      appTheme.item = (appTheme.item ?? []).filter((i) => i.$.name !== 'android:windowShowWallpaper');
      for (const i of appTheme.item) {
        if (i.$.name === 'android:windowBackground' && i._ === '@android:color/transparent') i._ = '@color/activityBackground';
      }
    }
    return cfg;
  });
}

const activitySource = (pkg) => `package ${pkg}

import android.os.Bundle
import androidx.activity.OnBackPressedCallback
import com.facebook.react.ReactActivity
import com.facebook.react.ReactActivityDelegate
import com.facebook.react.defaults.DefaultNewArchitectureEntryPoint.fabricEnabled
import com.facebook.react.defaults.DefaultReactActivityDelegate
import expo.modules.ReactActivityDelegateWrapper
import expo.modules.velouralauncher.VelouraLauncherModule

/** Veloura Home — renders the "launcher" JS component in its own task. Generated by plugins/withHomeMode.js. */
class LauncherActivity : ReactActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(null)
    // Back on the Home screen goes to JS as a launcher-only event (never to the app's navigation).
    onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
      override fun handleOnBackPressed() {
        VelouraLauncherModule.emitLauncherBack()
      }
    })
  }

  override fun getMainComponentName(): String = "launcher"

  override fun createReactActivityDelegate(): ReactActivityDelegate {
    return ReactActivityDelegateWrapper(
      this,
      BuildConfig.IS_NEW_ARCHITECTURE_ENABLED,
      object : DefaultReactActivityDelegate(this, mainComponentName, fabricEnabled) {}
    )
  }
}
`;

function findMainActivity(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const found = findMainActivity(full);
      if (found) return found;
    } else if (entry.name === 'MainActivity.kt') {
      return full;
    }
  }
  return null;
}

function withLauncherActivitySource(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const javaRoot = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java');
      const main = findMainActivity(javaRoot);
      if (!main) throw new Error('withHomeMode: MainActivity.kt not found');
      const pkg = fs.readFileSync(main, 'utf8').match(/^package\s+([\w.]+)/m)[1];
      fs.writeFileSync(path.join(path.dirname(main), 'LauncherActivity.kt'), activitySource(pkg));
      return cfg;
    },
  ]);
}

module.exports = function withHomeMode(config) {
  return withLauncherActivitySource(withLauncherTheme(withLauncherManifest(config)));
};
